#!/bin/sh
# Поднимает виртуальный экран и запускает то, что попросили.
#
# Почему не xvfb-run, как было сначала. Ему нужна программа xauth - она
# раздаёт права на доступ к экрану. В образе её нет: ставили xvfb с
# --no-install-recommends, ради размера, а xauth как раз в рекомендуемых.
# На живом сервере это вылезло как «xvfb-run: error: xauth command not
# found». Добавить xauth значило бы пересобрать слой, в котором качается
# браузер, - десять минут ради одной программы, без которой можно обойтись:
# права на доступ к экрану внутри контейнера некому спрашивать, там один
# пользователь.
#
# Заодно это делает экран общим для всех команд. Раньше xvfb-run стоял в
# CMD, а любая своя команда его подменяла - и проверка запускалась вовсе
# без экрана. Теперь экран поднимается всегда, что бы ни запускали.
Xvfb :99 -screen 0 1440x900x24 >/dev/null 2>&1 &
export DISPLAY=:99

# Дать серверу экрана секунду на запуск: браузер, стартовавший раньше него,
# не найдёт куда рисовать и молча свалится.
sleep 1

exec "$@"
