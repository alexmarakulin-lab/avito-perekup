# -*- coding: utf-8 -*-
"""Запуск бота с домашнего компьютера.

Проверяет настройки и объясняет по-русски, чего не хватает. Раньше эти
проверки жили в .bat-файле, но русский текст внутри него Windows читает не
в той кодировке и рассыпает на куски, пытаясь выполнить их как команды.
"""
import os
import socket
import subprocess
import sys
import time
from datetime import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)
sys.path.insert(0, HERE)

import env_file

RULER = "=" * 62


def fail(*lines):
    print("\n" + RULER)
    for line in lines:
        print("  " + line)
    print(RULER + "\n")
    sys.exit(1)


# Замок на второй запуск.
#
# Два бота разом - беда тихая и оттого злая. Telegram отдаёт сообщения
# только одному опросу, и второй бот их перехватывает через раз: половина
# нажатий просто пропадает. Вдобавок оба лезут в одну папку профиля
# браузера, а Chrome пускает туда только одного - и Авито перестаёт
# читаться у обоих.
#
# Замком служит занятый порт: он освобождается сам при закрытии окна, в
# отличие от файла-метки, которая после аварийного выхода осталась бы
# лежать и не пускала бы уже никого.
_lock_socket = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
try:
    _lock_socket.bind(("127.0.0.1", 47653))
    _lock_socket.listen(1)
except OSError:
    fail("Бот уже запущен в другом окне.",
         "",
         "Двух сразу быть не должно: они делят между собой сообщения",
         "из Telegram, и половина нажатий пропадает.",
         "",
         "Найди на панели задач чёрное окно, где бегут строки,",
         "и работай в нём. Если нужно перезапустить - сначала закрой",
         "то окно, и только потом запускай это.")

if not os.path.exists(os.path.join(HERE, ".env")):
    fail("Нет файла настроек.", "", "Запусти «Настроить бота» - он всё создаст и спросит.")

env_file.load()

if not os.getenv("AVITO_BOT_TOKEN"):
    fail("Не задан токен бота.", "", "Запусти «Настроить бота» и вставь токен от @BotFather.")

if not os.getenv("AVITO_OWNER_ID"):
    print("\n  Внимание: не задан твой номер - боту сможет писать кто угодно.")
    print("  Поправить можно через «Настроить бота».\n")

print(RULER)
print("  ПЕРЕКУП 23 - бот запускается")
print(RULER)
print("  Это окно закрывать нельзя: пока оно открыто, бот работает.")
print("  Если бот остановится - подниму его сам, окно трогать не нужно.")
print("  Остановить совсем - Ctrl+C или закрыть окно.")
print(RULER + "\n")

# ========== ПРИСМОТР ==========
# Бот запускается не здесь, а отдельным процессом, за которым этот
# приглядывает и поднимает заново, если тот вышел.
#
# Зачем понадобилось. Внутри бота живёт сторож связи: намолчал опрос
# Telegram три минуты - выходим, «пусть перезапустят». Писался он под
# сервер, где контейнер поднимает Docker. Дома поднимать было некому, и
# выход означал смерть насовсем.
#
# Так и вышло в ночь на 27.08.2026. Компьютер уснул в 20:39, утром
# проснулся, сторож увидел двенадцать часов молчания - и вышел. Бот не
# работал до вечера, и по логу это выглядело как «просто перестал».
#
# Сон компьютера этим не лечится: пока он спит, никто ничего не ищет.
# Лечится только тем, чтобы не давать ему засыпать.
RESTART_DELAY = 5
# Если бот падает сразу после запуска раз за разом - дело не в связи, а в
# поломке, и крутить бесконечный хоровод перезапусков незачем.
FAST_FAIL_LIMIT = 5
FAST_FAIL_SECONDS = 60


def stamp() -> str:
    return datetime.now().strftime("%H:%M:%S")


fast_fails = 0
while True:
    started = time.time()
    try:
        code = subprocess.call([sys.executable, "avito_bot.py"])
    except KeyboardInterrupt:
        print(f"\n  [{stamp()}] Остановлено вручную. До встречи.")
        break

    lived = time.time() - started
    fast_fails = fast_fails + 1 if lived < FAST_FAIL_SECONDS else 0

    if fast_fails >= FAST_FAIL_LIMIT:
        fail(f"Бот падает сразу после запуска, {FAST_FAIL_LIMIT} раз подряд.",
             "",
             "Это уже не обрыв связи, а поломка. Покажи последние строки выше -",
             "по ним будет видно, что именно сломалось.")

    # flush обязателен: когда вывод идёт не в окно, а в файл, Python
    # придерживает его в памяти, и сообщение о перезапуске туда не попадает
    # до самого конца работы - то есть ровно тогда, когда оно уже не нужно.
    print(f"\n  [{stamp()}] Бот остановился (код {code}), "
          f"проработав {int(lived // 60)} мин. Поднимаю заново через "
          f"{RESTART_DELAY} с.\n", flush=True)
    try:
        time.sleep(RESTART_DELAY)
    except KeyboardInterrupt:
        print(f"  [{stamp()}] Остановлено вручную. До встречи.")
        break
