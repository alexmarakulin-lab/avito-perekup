# -*- coding: utf-8 -*-
"""Запуск бота с домашнего компьютера.

Проверяет настройки и объясняет по-русски, чего не хватает. Раньше эти
проверки жили в .bat-файле, но русский текст внутри него Windows читает не
в той кодировке и рассыпает на куски, пытаясь выполнить их как команды.
"""
import os
import socket
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)
sys.path.insert(0, HERE)

import env_file

RULER = "=" * 62


def fail(*lines):
    print("\n" + RULER)
    for line in lines:
        print("  " + line)
    print(RULER + "\n")
    sys.exit(1)


# Замок на второй запуск.
#
# Два бота разом - беда тихая и оттого злая. Telegram отдаёт сообщения
# только одному опросу, и второй бот их перехватывает через раз: половина
# нажатий просто пропадает. Вдобавок оба лезут в одну папку профиля
# браузера, а Chrome пускает туда только одного - и Авито перестаёт
# читаться у обоих.
#
# Замком служит занятый порт: он освобождается сам при закрытии окна, в
# отличие от файла-метки, которая после аварийного выхода осталась бы
# лежать и не пускала бы уже никого.
_lock_socket = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
try:
    _lock_socket.bind(("127.0.0.1", 47653))
    _lock_socket.listen(1)
except OSError:
    fail("Бот уже запущен в другом окне.",
         "",
         "Двух сразу быть не должно: они делят между собой сообщения",
         "из Telegram, и половина нажатий пропадает.",
         "",
         "Найди на панели задач чёрное окно, где бегут строки,",
         "и работай в нём. Если нужно перезапустить - сначала закрой",
         "то окно, и только потом запускай это.")

if not os.path.exists(os.path.join(HERE, ".env")):
    fail("Нет файла настроек.", "", "Запусти «Настроить бота» - он всё создаст и спросит.")

env_file.load()

if not os.getenv("AVITO_BOT_TOKEN"):
    fail("Не задан токен бота.", "", "Запусти «Настроить бота» и вставь токен от @BotFather.")

if not os.getenv("AVITO_OWNER_ID"):
    print("\n  Внимание: не задан твой номер - боту сможет писать кто угодно.")
    print("  Поправить можно через «Настроить бота».\n")

print(RULER)
print("  ПЕРЕКУП 23 - бот запускается")
print(RULER)
print("  Это окно закрывать нельзя: пока оно открыто, бот работает.")
print("  Остановить - Ctrl+C или закрыть окно.")
print(RULER + "\n")

import avito_bot

avito_bot.build_app().run_polling(drop_pending_updates=True, allowed_updates=["message"])
